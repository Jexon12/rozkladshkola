import {defaultCalendar,ensureWeeklyVersion} from '../.sites-runtime/school-check.mjs';
import assert from 'node:assert/strict';
const origin='http://127.0.0.1:5173';
const login=await fetch(origin+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
const cookie=login.headers.getSetCookie().map(s=>s.split(';')[0]).join('; ');
assert.ok(cookie,'Local sign-in must issue a development cookie');
const headers={'Content-Type':'application/json',Cookie:cookie,Origin:origin};
let initial=await (await fetch(origin+'/api/schedule')).json();
const draft=structuredClone(initial.school);
ensureWeeklyVersion(draft,'2026-10-12').weekly['9-А'][0][0]={subject:'Математика',room:'М'};
draft.calendar=structuredClone(defaultCalendar);draft.calendar.daysOff.push({date:'2026-10-07',label:'Перевірка календаря',classes:['8']});
draft.weekly['8'][0][0].subject='Географія (перевірка збереження)';
const put=(school,revision,h=headers)=>fetch(origin+'/api/schedule',{method:'PUT',headers:h,body:JSON.stringify({school,revision})});
const unauth=await put(draft,initial.revision,{'Content-Type':'application/json'});assert.equal(unauth.status,401);
const saved=await put(draft,initial.revision);assert.equal(saved.status,200,await saved.clone().text());
const state=await saved.json();
const reloaded=await (await fetch(origin+'/api/schedule')).json();assert.equal(reloaded.school.weekly['8'][0][0].subject,draft.weekly['8'][0][0].subject);
assert.deepEqual(reloaded.school.calendar,draft.calendar);assert.deepEqual(reloaded.school.weeklyVersions,draft.weeklyVersions);
const stale=await put(initial.school,initial.revision);assert.equal(stale.status,409);
const restored=await put(initial.school,state.revision);assert.equal(restored.status,200);
const invalid=await put({...initial.school,version:99},state.revision+1);assert.equal(invalid.status,400);
console.log('API checks passed: authenticated saving, persistence after reload, stale-update conflict, validation and restoration of original schedule.');
